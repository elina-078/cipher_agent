class ActionPoolManager {
    constructor() {
        this.storageKey = 'spy_game_used_actions';
        this.customActionsKey = 'spy_game_custom_actions';
        this.init();
    }

    init() {
        this.usedIds = new Set(this.loadUsedIds());
        this.customActions = this.loadCustomActions();
    }

    loadUsedIds() {
        try {
            const data = localStorage.getItem(this.storageKey);
            return data ? JSON.parse(data) : [];
        } catch (e) {
            return [];
        }
    }

    saveUsedIds() {
        try {
            localStorage.setItem(this.storageKey, JSON.stringify(Array.from(this.usedIds)));
        } catch (e) {}
    }

    loadCustomActions() {
        try {
            const data = localStorage.getItem(this.customActionsKey);
            return data ? JSON.parse(data) : [];
        } catch (e) {
            return [];
        }
    }

    saveCustomActions() {
        try {
            localStorage.setItem(this.customActionsKey, JSON.stringify(this.customActions));
        } catch (e) {}
    }

    getAllActions() {
        return [...DEFAULT_ACTIONS, ...this.customActions];
    }

    getRemainingActions() {
        const all = this.getAllActions();
        return all.filter(a => !this.usedIds.has(a.id));
    }

    drawAction() {
        const all = this.getAllActions();
        if (all.length === 0) return null;

        // Выбираем действие случайным образом из всей базы:
        // выбранное действие НЕ убирается из списка возможных последующих
        const randomIndex = Math.floor(Math.random() * all.length);
        const chosen = all[randomIndex];

        return {
            action: chosen,
            remainingCount: all.length,
            totalCount: all.length
        };
    }

    resetPool() {
        this.usedIds.clear();
        this.saveUsedIds();
    }

    addCustomAction(text, hint = '') {
        const newId = 'custom_' + Date.now();
        const action = { id: newId, text: text.trim(), hint: hint.trim() || 'Выполняйте незаметно во время игры.' };
        this.customActions.push(action);
        this.saveCustomActions();
        return action;
    }
}

// Экспортируем глобальный экземпляр
const _root = (typeof window !== 'undefined') ? window : ((typeof global !== 'undefined') ? global : this);
_root.actionPool = new ActionPoolManager();
if (typeof window !== 'undefined') {
    window.actionPool = _root.actionPool;
}
